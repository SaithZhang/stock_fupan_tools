# ==============================================================================
# 🛡️ 核心选股过滤器 V4.0 (src/core/filter.py)
# 策略：VIP白名单 + 市场风暴眼 + 强流动性核心
# ==============================================================================
from typing import List, Dict, Set
from src.core.domain import Stock


class StockFilter:
    """
    V4.0 核心思想：聚焦 300 只核心标的。
    只看：持仓/大佬作业 + 涨跌停/炸板 + 巨量/高换手的筹码优选股。
    """

    def check(self, stock: Stock, tags: List[str], context: Dict) -> bool:
        """
        :param stock: 股票对象
        :param tags: 策略命中的标签
        :param context: 上下文 (包含 holdings, f_lao, manual 等白名单)
        :return: True(保留) / False(剔除)
        """
        symbol = stock.code  # 6位代码 (e.g., '600519')

        # ----------------------------------------------------------------------
        # 1. 👑 VIP 白名单 (无条件入池)
        # ----------------------------------------------------------------------
        # 无论今日表现如何，只要在关注名单里，必须留下复盘
        if symbol in context.get('holdings', []) or \
                symbol in context.get('f_lao', []) or \
                symbol in context.get('manual', []):
            return True

        # ----------------------------------------------------------------------
        # 2. 🔥 市场风暴眼 (情绪核心)
        # ----------------------------------------------------------------------
        # 涨停、跌停、炸板。这是市场情绪的最直接反应。
        if stock.is_zt or stock.is_dt or stock.is_broken:
            return True

        # ----------------------------------------------------------------------
        # 3. 🌊 趋势大票 & 筹码核心 (严苛筛选)
        # ----------------------------------------------------------------------
        # 如果不是VIP也不是板，要想进入复盘池，必须是“有资金运作的核心票”。
        # 以前 800 多个回踩票大都是缩量阴跌的，这里全部砍掉。

        # 前置条件：必须命中了至少一个策略 (否则根本没看的必要)
        if not tags:
            return False

        # 资金门槛 (三选一，满足其一即可)：
        # 1. 大屁股：成交额 > 8亿 (机构或大游资主战场，如中科曙光、宁德时代)
        # 2. 强换手：换手率 > 7% (只有活跃的票才有博弈价值)
        # 3. 强表态：涨幅 > 5% (大阳线确认，哪怕成交额稍小也算强势)
        is_big_money = stock.amount >= 800_000_000
        is_active_turnover = stock.turnover >= 7.0
        is_strong_signal = stock.pct >= 5.0

        if is_big_money or is_active_turnover or is_strong_signal:
            return True

        # ----------------------------------------------------------------------
        # 4. 🗑️ 其他一律剔除
        # ----------------------------------------------------------------------
        # 那些成交额 2亿、换手 1%、只是碰了一下均线的“回踩股”，统统不要。
        return False